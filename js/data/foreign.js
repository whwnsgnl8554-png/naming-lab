// 본명 뜻 자유 입력을 키워드 배열로 변환
//   '지혜로운 봄꽃' → ['지혜', '봄', '꽃']
export function 뜻에서한자훈(뜻텍스트, 본명원어 = '') {
  if (!뜻텍스트 && !본명원어) return [];
  const result = new Set();
  // 1) 자유 텍스트에서 키워드 추출
  const tokens = (뜻텍스트 || '').toLowerCase()
    .split(/[\s,，、·:;.()\[\]{}'"!?\/]+/)
    .filter(Boolean);
  for (const t of tokens) {
    if (MEANING_TO_HANJA[t]) {
      for (const w of MEANING_TO_HANJA[t]) result.add(w);
    }
    // 부분 매칭 (한국어 단어 안에 키가 들어있는 경우)
    for (const key of Object.keys(MEANING_TO_HANJA)) {
      if (key.length >= 2 && t.includes(key)) {
        for (const w of MEANING_TO_HANJA[key]) result.add(w);
      }
    }
  }
  // 2) 본명 자체가 흔한 이름이면 디폴트 뜻 가산
  const cleanName = (본명원어 || '').toLowerCase().replace(/\s+/g, '');
  if (NAME_TO_MEANINGS[cleanName]) {
    for (const meaning of NAME_TO_MEANINGS[cleanName]) {
      if (MEANING_TO_HANJA[meaning]) {
        for (const w of MEANING_TO_HANJA[meaning]) result.add(w);
      }
    }
  }
  return [...result];
}
