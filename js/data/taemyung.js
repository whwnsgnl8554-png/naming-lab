export function 예정월에서계절(월) {
  if (!월) return null;
  if (월 >= 3 && 월 <= 5) return '봄';
  if (월 >= 6 && 월 <= 8) return '여름';
  if (월 >= 9 && 월 <= 11) return '가을';
  return '겨울';
}
