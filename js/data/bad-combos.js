// 성+이름 놀림 체크 — true면 안전, false면 배제
export function 조합안전한가(성, 이름) {
  if (!성 || !이름) return true;
  const 풀네임 = 성 + 이름;

  // 1) 전체 이름 블랙리스트
  if (BAD_FULLNAMES.has(풀네임)) return false;

  // 2) 성별 이름 블랙리스트
  const 성별금기 = BAD_BY_SURNAME[성] || [];
  if (성별금기.includes(이름)) return false;

  // 3) 이름 자체가 부적절 어감
  if (BAD_UNIVERSAL.has(이름)) return false;

  // 4) 성+이름 첫 글자로 시작하는 놀림 단어 (예: 이+뻐 = 이뻐)
  //    풀네임의 앞 2~3글자가 흔한 놀림 단어면 제외
  const 앞두글자 = 풀네임.slice(0, 2);
  if (BAD_FULLNAMES.has(앞두글자)) return false;

  return true;
}
