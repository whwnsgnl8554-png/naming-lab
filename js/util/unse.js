// ─── 메인 진입점 ───
// pillars: { 연주, 월주, 일주, 시주 } 각각 { 천:{자,음,오,음양}, 지:{자,음,오,띠} }
// 시주는 null 가능
export function 운세분석(pillars) {
  if (!pillars || !pillars.일주) return null;
  const 일간오행 = pillars.일주.천.오;
  const 일간음양 = pillars.일주.천.음양;
  const 일간자 = pillars.일주.천.자;

  // 모든 타 천간·지지에 대해 십성 카운트
  const ship = {
    비견: 0, 겁재: 0, 식신: 0, 상관: 0, 편재: 0,
    정재: 0, 편관: 0, 정관: 0, 편인: 0, 정인: 0,
  };
  const 모든기둥 = ['연주', '월주', '일주', '시주']
    .map(k => pillars[k]).filter(Boolean);
  for (const p of 모든기둥) {
    if (p === pillars.일주) {
      // 일주는 지지만 카운트 (천간은 자기 자신=일간)
      const s = 십성결정(일간오행, 일간음양, p.지.오, 음양추정(p.지.자));
      if (s) ship[s]++;
    } else {
      const st = 십성결정(일간오행, 일간음양, p.천.오, p.천.음양);
      if (st) ship[st]++;
      const sj = 십성결정(일간오행, 일간음양, p.지.오, 음양추정(p.지.자));
      if (sj) ship[sj]++;
    }
  }

  // 신살 검출
  const 지지목록 = 모든기둥.map(p => p.지.자);
  const 신살 = [];
  if ((천을귀인표[일간자] || []).some(z => 지지목록.includes(z))) {
    신살.push({ id: 'cheonul', 이름: '천을귀인 (天乙貴人)', 설명: '평생 결정적인 순간에 도와주는 귀인을 만날 운.' });
  }
  if (지지목록.some(z => 도화지지.includes(z))) {
    신살.push({ id: 'dohwa', 이름: '도화살 (桃花)', 설명: '사람을 끄는 매력·인기. 예체능·사람 만나는 일에 강점.' });
  }
  const 연지 = pillars.연주.지.자;
  if (역마표[연지] && 지지목록.includes(역마표[연지])) {
    신살.push({ id: 'yeokma', 이름: '역마살 (驛馬)', 설명: '이동·변화·해외와 인연. 한 자리에 묶이지 않는 활동성.' });
  }
  if (문창표[일간자] && 지지목록.includes(문창표[일간자])) {
    신살.push({ id: 'munchang', 이름: '문창귀인 (文昌)', 설명: '학업·글·말솜씨에 타고난 재능.' });
  }
  if (양인표[일간자] && 지지목록.includes(양인표[일간자])) {
    신살.push({ id: 'yangin', 이름: '양인 (羊刃)', 설명: '강력한 추진력과 카리스마. 결단력 ↑.' });
  }

  // ─── 8가지 운세 점수 (0~100) ───
  const cap = v => Math.max(0, Math.min(100, v));
  const has = id => 신살.some(s => s.id === id) ? 12 : 0;

  const 운세 = {
    금전: {
      이름: '금전운',
      아이콘: '💰',
      점수: cap(40 + (ship.정재 + ship.편재) * 18 - ship.겁재 * 8 + has('cheonul')),
      코멘트: 코멘트('금전', ship),
    },
    건강: {
      이름: '건강·식복',
      아이콘: '🌿',
      점수: cap(50 + ship.식신 * 14 + ship.정인 * 6 - ship.편관 * 5),
      코멘트: 코멘트('건강', ship),
    },
    장수: {
      이름: '장수·안정',
      아이콘: '🪷',
      점수: cap(45 + (ship.정인 + ship.식신) * 10 - (ship.편관 + ship.겁재) * 4 + (지지목록.includes('辰') || 지지목록.includes('丑') ? 8 : 0)),
      코멘트: 코멘트('장수', ship),
    },
    인간관계: {
      이름: '원만한 인간관계',
      아이콘: '🤝',
      점수: cap(40 + ship.비견 * 8 + ship.식신 * 10 + has('cheonul') + has('dohwa') - ship.겁재 * 10),
      코멘트: 코멘트('인간관계', ship),
    },
    관리자: {
      이름: '관리자·리더십',
      아이콘: '👑',
      점수: cap(40 + ship.정관 * 18 + ship.편관 * 10 + ship.정인 * 6 + has('yangin')),
      코멘트: 코멘트('관리자', ship),
    },
    학업: {
      이름: '학업·지혜',
      아이콘: '📚',
      점수: cap(40 + (ship.정인 + ship.편인) * 14 + ship.식신 * 5 + has('munchang')),
      코멘트: 코멘트('학업', ship),
    },
    창의: {
      이름: '창의·예술',
      아이콘: '🎨',
      점수: cap(40 + ship.상관 * 16 + ship.편인 * 10 + has('dohwa')),
      코멘트: 코멘트('창의', ship),
    },
    인기: {
      이름: '인기·매력',
      아이콘: '✨',
      점수: cap(40 + ship.상관 * 8 + ship.식신 * 6 + has('dohwa') * 1.5 + has('cheonul') * 0.7),
      코멘트: 코멘트('인기', ship),
    },
  };

  // 일간 강도 — 자기 오행 + 인성(인) 빈도로 신강/신약 판정
  const 일간기운 = ship.비견 + ship.겁재 + ship.정인 + ship.편인;
  const 신강신약 = 일간기운 >= 4 ? '신강' : 일간기운 <= 1 ? '신약' : '중화';

  return {
    일간: { 자: 일간자, 오: 일간오행, 음양: 일간음양 },
    십성카운트: ship,
    신살,
    운세,
    신강신약,
    종합: 종합코멘트(운세, 신강신약),
  };
}

// 지지의 음양 추정 — 자인진오신술=陽, 축묘사미유해=陰
function 음양추정(지자) {
  return ['子', '寅', '辰', '午', '申', '戌'].includes(지자) ? '陽' : '陰';
}

