export function 수리길흉(n) {
  const v = ((n - 1) % 81) + 1;
  if (길수.has(v)) return { 길흉: '길', 수: v };
  if (흉수.has(v)) return { 길흉: '흉', 수: v };
  return { 길흉: '평', 수: v };
}
