// 보강 운세 키워드 → 한자 가중치 매칭에 사용할 훈 풀 통합
export function 보강가중(보강운세, h) {
  if (!보강운세?.length) return 0;
  let w = 0;
  for (const k of 보강운세) {
    const def = UNSE_HANJA[k];
    if (!def) continue;
    if (def.훈매칭.some(t => h.훈.includes(t))) w += 12;
  }
  return w;
}
