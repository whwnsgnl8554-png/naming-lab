function 종합코멘트(운세, 신강신약) {
  const 정렬 = Object.entries(운세).sort((a, b) => b[1].점수 - a[1].점수);
  const top2 = 정렬.slice(0, 2).map(([_, v]) => v.이름).join('·');
  const bot1 = 정렬[정렬.length - 1][1].이름;
  return `이 사주는 ${top2} 쪽으로 결이 가장 잘 흐르고, ${bot1}은 의식적으로 보강해주면 좋아요. 일간은 ${신강신약} — ${
    신강신약 === '신강' ? '주도성이 강해 본인의 결정을 따라가는 게 잘 맞음.'
    : 신강신약 === '신약' ? '주변의 도움·환경을 잘 활용하면 가속이 붙는 톤.'
    : '균형이 잡힌 사주 — 다양한 길에 잘 적응함.'
  }`;
}
