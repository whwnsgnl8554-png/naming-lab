// 사주 → 운세 분석
// 전통 명리학의 십성(十星) + 신살(神煞) 일부를 단순화해 8가지 운세 점수 도출.
// 학파마다 해석 다름 — 참고용으로 명시.
//
// 십성(일간 기준 다른 천간·지지의 관계):
//  - 비견(比肩): 같은 오행 + 같은 음양 → 동료·형제
//  - 겁재(劫財): 같은 오행 + 다른 음양 → 경쟁·재물 손실
//  - 식신(食神): 일간이 생하는 + 같은 음양 → 표현·식복·건강
//  - 상관(傷官): 일간이 생하는 + 다른 음양 → 창의·재능
//  - 편재(偏財): 일간이 극하는 + 같은 음양 → 큰 재물·사업
//  - 정재(正財): 일간이 극하는 + 다른 음양 → 안정적 재물
//  - 편관(偏官): 일간을 극하는 + 같은 음양 → 권력·카리스마(=七殺)
//  - 정관(正官): 일간을 극하는 + 다른 음양 → 명예·관리자
//  - 편인(偏印): 일간을 생하는 + 같은 음양 → 직관·예술
//  - 정인(正印): 일간을 생하는 + 다른 음양 → 학업·지혜

const 상생 = { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' };
const 상극 = { 木: '土', 土: '水', 水: '火', 火: '金', 金: '木' };

function 십성결정(일간오행, 일간음양, 타오행, 타음양) {
  const sameYin = 일간음양 === 타음양;
  if (일간오행 === 타오행) return sameYin ? '비견' : '겁재';
  if (상생[일간오행] === 타오행) return sameYin ? '식신' : '상관';
  if (상극[일간오행] === 타오행) return sameYin ? '편재' : '정재';
  if (상생[타오행] === 일간오행) return sameYin ? '편인' : '정인';
  if (상극[타오행] === 일간오행) return sameYin ? '편관' : '정관';
  return null;
}

