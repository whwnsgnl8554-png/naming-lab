// ─── 이름이 어느 연도 인기였는지 찾기 (뱃지용) ───
//   가장 최근 발현 연도 + 순위 반환
export function 인기랭킹(이름, 성별) {
  const map = 성별 === 'm' ? POPULAR_M : POPULAR_F;
  const yearsDesc = Object.keys(map).map(Number).sort((a,b) => b-a);
  for (const y of yearsDesc) {
    const idx = map[y].indexOf(이름);
    if (idx >= 0) return { 연도: y, 순위: idx + 1 };
  }
  return null;
}

// ─── 가중치 산정 (작명 시 사용) ───
//   출생 연도 가까운 인기일수록 + 폭 큼
export function 인기가중(이름, 성별, 출생연도) {
  if (!이름) return 0;
  const r = 인기랭킹(이름, 성별);
  if (!r) return 0;

  // 순위 가산 (1위 +18, 10위 +12, 20위 +6)
  let 순위가산 = Math.max(0, 22 - r.순위);

  // 출생연도와 인기연도의 거리 — 가까울수록 +↑
  let 시기가산 = 0;
  if (!출생연도) {
    // 출생연도 모르면 최근 5년이 가장 강함
    if (r.연도 >= 2020) 시기가산 = 14;
    else if (r.연도 >= 2014) 시기가산 = 6;
    else 시기가산 = 2;
  } else {
    const diff = Math.abs(r.연도 - 출생연도);
    if (diff <= 2) 시기가산 = 16;
    else if (diff <= 5) 시기가산 = 10;
    else if (diff <= 10) 시기가산 = 4;
    else 시기가산 = 0;
  }
  return 순위가산 + 시기가산;
}
